export type SuitabilityRoleTemplate = {
  id: string;
  title: string;
  category: string;
  defaultIndustry: string;
  defaultSeniority: SuitabilityLevelId;
  coreSkills: string[];
  toolOptions: string[];
  focusOptions: string[];
  /** What this role actually does — shown on catalog cards. */
  description: string;
};

function role(
  id: string,
  title: string,
  category: string,
  defaultIndustry: string,
  description: string,
  coreSkills: string[],
  toolOptions: string[],
  focusOptions: string[],
  defaultSeniority: SuitabilityLevelId = "mid",
): SuitabilityRoleTemplate {
  return {
    id,
    title,
    category,
    defaultIndustry,
    defaultSeniority,
    coreSkills,
    toolOptions,
    focusOptions,
    description,
  };
}

