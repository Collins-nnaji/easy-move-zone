export function getSuitabilityRoleById(id: string): SuitabilityRoleTemplate | undefined {
  return SUITABILITY_ROLE_TEMPLATES.find((r) => r.id === id);
}

export function listSuitabilityCategories(): Array<{ id: string; label: string; count: number }> {
  return SUITABILITY_CATEGORIES.map((c) => ({
    ...c,
    count: SUITABILITY_ROLE_TEMPLATES.filter((r) => r.category === c.id).length,
  })).filter((c) => c.count > 0);
}
