/**
 * Finds a permanent logo for a company using fuzzy matching
 * @param companyName - The company name to search for
 * @returns The logo URL if found, null otherwise
 */
export function getPermanentLogo(companyName: string): string | null {
  if (!companyName) return null;
  
  const normalizedInput = companyName.toLowerCase().trim().replace(/ (uk|ltd|limited|inc|corp|corporation)$/g, '');
  
  // Direct exact match first (case-insensitive keys)
  for (const [key, value] of Object.entries(PERMANENT_LOGOS)) {
    const normalizedKey = key.toLowerCase().trim().replace(/ (uk|ltd|limited|inc|corp|corporation)$/g, '');
    if (normalizedInput === normalizedKey) {
      return value;
    }
  }
  
  // Fuzzy matching for partial inclusions
  const possibleMatches = Object.keys(PERMANENT_LOGOS).filter(key => {
    const normalizedKey = key.toLowerCase().trim().replace(/ (uk|ltd|limited|inc|corp|corporation)$/g, '');
    return normalizedInput.includes(normalizedKey) || normalizedKey.includes(normalizedInput);
  });
  
  if (possibleMatches.length > 0) {
    // Sort by length - shorter matches are usually more accurate
    possibleMatches.sort((a, b) => a.length - b.length);
    return PERMANENT_LOGOS[possibleMatches[0]];
  }
  
  return null;
}

/**
 * Checks if a company has a permanent logo available
 * @param companyName - The company name to check
 * @returns True if a permanent logo exists
 */
export function hasPermanentLogo(companyName: string): boolean {
  return getPermanentLogo(companyName) !== null;
}