export const WORLD_COUNTRIES: CountryOption[] = COUNTRY_NAMES.map((name) => ({
  name,
  slug: SLUG_OVERRIDES[name] ?? slugify(name),
}))

export const WORLD_COUNTRY_NAMES = WORLD_COUNTRIES.map((c) => c.name)

export function getCountryBySlug(slug: string): CountryOption | undefined {
  return WORLD_COUNTRIES.find((c) => c.slug === slug)
}

export function getCountryByName(name: string): CountryOption | undefined {
  const needle = name.trim().toLowerCase()
  return WORLD_COUNTRIES.find((c) => c.name.toLowerCase() === needle)
}
